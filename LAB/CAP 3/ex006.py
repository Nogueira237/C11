# lista com ingredientes de uma receita de bolo
ingredientes = ['farinha', 'leite', 'ovos', 'fermento', 'açucar']
print(ingredientes)

# adiciona um novo ingrediente no final
ingredientes.append('fuba')
print(ingredientes)

# insere outro em uma posição especifíca
ingredientes.insert(1, 'sal')
print(ingredientes)

# remove um ingrediente pelo valor
ingredientes.remove('ovos')
print(ingredientes)